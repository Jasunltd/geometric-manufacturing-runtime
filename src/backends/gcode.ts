import { semanticDigest } from "../integrity/canonical.js";
import type {
  ExecutionPlan,
  GCodeArtifact,
  MotionPrimitive,
  Point2,
} from "../model.js";

function fmt(value: number): string {
  const normalized = Math.abs(value) < 1e-12 ? 0 : value;
  return normalized.toFixed(6).replace(/\.0+$/, "").replace(/(\.\d*?)0+$/, "$1");
}

function xy(point: Point2): string {
  return `X${fmt(point.x)} Y${fmt(point.y)}`;
}

function centerlineLines(
  motion: Extract<MotionPrimitive, { readonly _tag: "CenterlineSweep" }>,
  plan: ExecutionPlan,
): readonly string[] {
  return [
    `(operation ${motion.operationId} centerline)`,
    `G0 Z${fmt(plan.safeZ)}`,
    `G0 ${xy(motion.start)}`,
    `G1 Z${fmt(motion.z)} F${fmt(plan.feedMmPerMin)}`,
    `G1 ${xy(motion.end)} F${fmt(plan.feedMmPerMin)}`,
    `G0 Z${fmt(plan.safeZ)}`,
  ];
}

function boundaryLines(
  motion: Extract<MotionPrimitive, { readonly _tag: "OffsetCapsuleBoundarySweep" }>,
  plan: ExecutionPlan,
): readonly string[] {
  const dx = motion.end.x - motion.start.x;
  const dy = motion.end.y - motion.start.y;
  const length = Math.hypot(dx, dy);
  if (length <= 0) {
    throw new TypeError(`operation ${motion.operationId} has zero-length offset boundary`);
  }

  const nx = -dy / length;
  const ny = dx / length;
  const d = motion.offsetRadius;

  const p1 = { x: motion.start.x + nx * d, y: motion.start.y + ny * d };
  const p2 = { x: motion.end.x + nx * d, y: motion.end.y + ny * d };
  const p3 = { x: motion.end.x - nx * d, y: motion.end.y - ny * d };
  const p4 = { x: motion.start.x - nx * d, y: motion.start.y - ny * d };

  return [
    `(operation ${motion.operationId} measured-tool boundary compensation)`,
    `G0 Z${fmt(plan.safeZ)}`,
    `G0 ${xy(p1)}`,
    `G1 Z${fmt(motion.z)} F${fmt(plan.feedMmPerMin)}`,
    `G1 ${xy(p2)} F${fmt(plan.feedMmPerMin)}`,
    `G2 ${xy(p3)} I${fmt(motion.end.x - p2.x)} J${fmt(motion.end.y - p2.y)} F${fmt(plan.feedMmPerMin)}`,
    `G1 ${xy(p4)} F${fmt(plan.feedMmPerMin)}`,
    `G2 ${xy(p1)} I${fmt(motion.start.x - p4.x)} J${fmt(motion.start.y - p4.y)} F${fmt(plan.feedMmPerMin)}`,
    `G0 Z${fmt(plan.safeZ)}`,
  ];
}

export function lowerExecutionPlanToGcode(plan: ExecutionPlan): GCodeArtifact {
  const lines: string[] = [
    "%",
    "(generated by geometric-manufacturing-runtime)",
    `(plan ${plan.planDigest})`,
    `(canonical geometry ${plan.canonicalGeometryDigest})`,
    "G21",
    "G90",
    "G17",
    plan.workOffset,
  ];

  for (const motion of plan.motion) {
    switch (motion._tag) {
      case "CenterlineSweep":
        lines.push(...centerlineLines(motion, plan));
        break;
      case "OffsetCapsuleBoundarySweep":
        lines.push(...boundaryLines(motion, plan));
        break;
    }
  }

  lines.push(`G0 Z${fmt(plan.safeZ)}`, "M30", "%");
  const text = `${lines.join("\n")}\n`;
  const artifactDigest = semanticDigest({
    backend: "generic-rs274",
    planDigest: plan.planDigest,
    text,
  });

  return {
    _tag: "GCodeArtifact",
    backend: "generic-rs274",
    planDigest: plan.planDigest,
    artifactDigest,
    text,
  };
}
